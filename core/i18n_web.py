def resolve_web_language(request):
    lang = (
        request.session.get('_language')
        or request.COOKIES.get(settings.LANGUAGE_COOKIE_NAME)
        or (request.user.preferred_language if getattr(request, 'user', None) and request.user.is_authenticated else None)
        or 'uz'
    )
    lang = str(lang).split('-')[0].lower()
    if lang not in WEB_STRINGS:
        lang = 'uz'
    return lang


def web_translations(request):
    lang = resolve_web_language(request)
    return {
        'active_lang': lang,
        't': WEB_STRINGS[lang],
    }
